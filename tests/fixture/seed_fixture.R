# Copies a small subset of the production database into an empty staging
# database that already has the production schema. Run through seed.sh, which
# creates the staging database and dumps the result to fixture.sql.
#
# Source: the `SEED_SOURCE_CONFIG` profile of config.yml (default: "default").
# Target: the staging container started by seed.sh (STAGING_PORT).

suppressPackageStartupMessages({
  library(DBI)
  library(glue)
})

# Small genes chosen to cover every case the tests need (checked by
# tests/testthat/test-fixture.R):
#   - minus strand: HBB, INS; plus strand: HBA1, CNN2, SMN1
#   - SMN1 has splice sites with many events (more than one table page)
#   - every gene is in both datasets and both transcript types
fixture_genes <- c("CNN2", "HBA1", "HBB", "INS", "SMN1")

source_profile <- Sys.getenv("SEED_SOURCE_CONFIG", "default")
src_args <- config::get("dataconnection", config = source_profile, file = "config.yml")
src <- dbConnect(RPostgres::Postgres(),
                 dbname = src_args$dbname, host = src_args$host, port = src_args$port,
                 user = src_args$user, password = src_args$password)
dst <- dbConnect(RPostgres::Postgres(),
                 dbname = "postgres", host = "localhost",
                 port = as.integer(Sys.getenv("STAGING_PORT", "55433")),
                 user = "postgres", password = "staging")

append_rows <- function(table, rows) {
  rows$rn <- NULL
  dbAppendTable(dst, Id(schema = "misspl_app", table = table), rows)
  message(sprintf("%-32s %7d rows", table, nrow(rows)))
  invisible(rows)
}

copy_rows <- function(table, sql) append_rows(table, dbGetQuery(src, sql))

# Keeps the canonical transcript and the first non-canonical one per gene and
# transcript type. `canonical_expr` is how the table encodes "canonical".
pick_tx <- function(table, canonical_expr) {
  glue_sql("SELECT * FROM (
              SELECT t.*, ROW_NUMBER() OVER (
                       PARTITION BY gene_name, transcript_type, ({canonical_expr})
                       ORDER BY tx_id) AS rn
                FROM misspl_app.{`table`} t
               WHERE gene_name IN ({fixture_genes*})) x
             WHERE rn = 1",
           canonical_expr = SQL(canonical_expr), .con = src)
}

ids_sql <- function(ids) glue_sql("{ids*}", .con = src)

# Identity columns are GENERATED ALWAYS; allow explicit ids while seeding.
for (tbl in c("misspl_events_300k_hg38_tx", "misspl_events_40k_hg19_tx")) {
  invisible(dbExecute(dst, glue_sql("ALTER TABLE misspl_app.{`tbl`} ALTER COLUMN gene_tx_id SET GENERATED BY DEFAULT", .con = dst)))
}

# Reference tables copied whole (small).
copy_rows("ref_tissues", "SELECT * FROM misspl_app.ref_tissues")

# 300K-RNA (hg38), normalised tables used by the dropdowns and event queries.
tx <- copy_rows("ref_tx", pick_tx("ref_tx", "canonical"))
tx_ids <- ids_sql(tx$transcript_id)

exons <- copy_rows("ref_exons", glue("SELECT * FROM misspl_app.ref_exons WHERE transcript_id IN ({tx_ids})"))
exon_ids <- ids_sql(exons$exon_id)
copy_rows("ref_splice_sites", glue("SELECT * FROM misspl_app.ref_splice_sites WHERE exon_id IN ({exon_ids})"))

# missplicing_stats is only indexed on exon_id, so filter on that first.
stats <- dbGetQuery(src, glue(
  "SELECT * FROM misspl_app.missplicing_stats
    WHERE exon_id IN ({exon_ids}) AND transcript_id IN ({tx_ids})"))
copy_rows("ref_missplicing_event", glue(
  "SELECT * FROM misspl_app.ref_missplicing_event
    WHERE misspl_event_id IN ({ids_sql(unique(stats$misspl_event_id))})"))
append_rows("missplicing_stats", stats)
copy_rows("tissue_missplicing_stats", glue(
  "SELECT * FROM misspl_app.tissue_missplicing_stats
    WHERE misspl_stat_id IN ({ids_sql(stats$misspl_stat_id)})"))

# 300K-RNA (hg38), flat tables used by Variant mode. Same transcripts as above.
tx300 <- copy_rows("misspl_events_300k_hg38_tx", glue_sql(
  "SELECT * FROM misspl_app.misspl_events_300k_hg38_tx
    WHERE gene_name IN ({fixture_genes*}) AND tx_id IN ({tx$tx_id*})", .con = src))
copy_rows("misspl_events_300k_hg38_events", glue(
  "SELECT * FROM misspl_app.misspl_events_300k_hg38_events WHERE gene_tx_id IN ({ids_sql(tx300$gene_tx_id)})"))

# 40K-RNA (hg19).
tx40 <- copy_rows("misspl_events_40k_hg19_tx", pick_tx("misspl_events_40k_hg19_tx", "canonical = 1"))
copy_rows("misspl_events_40k_hg19_events", glue(
  "SELECT * FROM misspl_app.misspl_events_40k_hg19_events WHERE gene_tx_id IN ({ids_sql(tx40$gene_tx_id)})"))

for (tbl in c("misspl_events_300k_hg38_tx", "misspl_events_40k_hg19_tx")) {
  invisible(dbExecute(dst, glue_sql("ALTER TABLE misspl_app.{`tbl`} ALTER COLUMN gene_tx_id SET GENERATED ALWAYS", .con = dst)))
}

dbDisconnect(src)
dbDisconnect(dst)
