# Query plans for the events table queries, from the full-size database. Run
# it from the repository root on the host, not in the test container:
#
#   Rscript tests/benchmark/query_plans.R <label>
#
# It reads the database settings from .env and writes
# tests/benchmark/query_plans/<label>.md. It is not part of the test suite and
# CI does not run it: the fixture database is too small for its plans to mean
# anything. Findings from these plans are written up in
# tests/benchmark/query_plans.md.
#
# The session is read-only and every statement times out after 120 s.
# EXPLAIN ANALYZE runs each query, so each run costs the database what a user
# clicking Generate Table does, three times per query.
#
# The SQL is the app's own, from misspl_stats_query() in helpers.R, with every
# "Show all" box ticked (no limit, exon skipping or cryptic filter). Each query
# runs for a typical gene (CNN2) and a large one (TTN, at its splice site with
# the most events). Each runs three times; the plan kept is the last, with
# warm caches, and the execution time of every run is listed.

suppressPackageStartupMessages(source("dependencies.R"))

label <- commandArgs(trailingOnly = TRUE)[1]
if (is.na(label) || !grepl("^[A-Za-z0-9_-]+$", label)) {
  stop("Usage: Rscript tests/benchmark/query_plans.R <label>  (letters, digits, - and _)")
}
if (!file.exists(".env")) stop("Run from the repository root, with .env present")
readRenviron(".env")

# helpers.R quotes values and queries through a global con.
con <- dbConnect(RPostgres::Postgres(),
                 dbname = Sys.getenv("DB_NAME"), host = Sys.getenv("DB_HOST"), port = 5432,
                 user = Sys.getenv("DB_USER"), password = Sys.getenv("DB_PASSWORD"))
on.exit(dbDisconnect(con), add = TRUE)
invisible(dbExecute(con, "SET default_transaction_read_only = on"))
invisible(dbExecute(con, "SET statement_timeout = '120s'"))
source("helpers.R")

runs <- 3

# 300K-RNA (hg38) takes ref_tx and ref_exons ids; 40K-RNA (hg19) takes the
# transcript and exon number as shown in the dropdowns.
ids_300k <- function(tx_id, exon_no) {
  dbGetQuery(con, glue_sql(
    "SELECT rt.transcript_id, re.exon_id
       FROM misspl_app.ref_tx rt
       JOIN misspl_app.ref_exons re ON re.transcript_id = rt.transcript_id
      WHERE rt.tx_id = {tx_id} AND re.exon_no = {exon_no}", .con = con))
}

sites <- list(
  list(gene = "CNN2", tx_id = "NM_001303501", exon_no = 2L, ss_type = "donor",
       tissue_id = 5L, tissue = "Whole Blood"),
  list(gene = "TTN", tx_id = "NM_001267550", exon_no = 48L, ss_type = "acceptor",
       tissue_id = 30L, tissue = "Muscle - Skeletal")
)

queries <- list()
for (site in sites) {
  ids <- ids_300k(site$tx_id, site$exon_no)
  stopifnot(nrow(ids) == 1)
  where <- sprintf("%s %s exon %d %s", site$gene, site$tx_id, site$exon_no, site$ss_type)
  queries[[length(queries) + 1]] <- list(
    title = paste("40K-RNA (hg19),", where),
    sql = misspl_stats_query("40K-RNA (hg19)", site$ss_type, as.character(site$exon_no),
                             site$tx_id, events_limit = 5L))
  queries[[length(queries) + 1]] <- list(
    title = paste("300K-RNA (hg38) all tissues,", where),
    sql = misspl_stats_query("300K-RNA (hg38)", site$ss_type, ids$exon_id, ids$transcript_id,
                             tissue_id = 0L, events_limit = 5L))
  queries[[length(queries) + 1]] <- list(
    title = sprintf("300K-RNA (hg38) one tissue (%s), %s", site$tissue, where),
    sql = misspl_stats_query("300K-RNA (hg38)", site$ss_type, ids$exon_id, ids$transcript_id,
                             tissue_id = site$tissue_id, events_limit = 5L))
}

explain <- function(sql) {
  plan <- dbGetQuery(con, paste("EXPLAIN (ANALYZE, BUFFERS, SETTINGS)", sql))[[1]]
  ms <- as.numeric(sub(".*Execution Time: ([0-9.]+) ms.*", "\\1",
                       grep("Execution Time", plan, value = TRUE)))
  list(plan = plan, ms = ms)
}

git <- function(args) tryCatch(system2("git", args, stdout = TRUE, stderr = FALSE),
                               error = function(e) "unknown")
dirty <- length(git(c("status", "--porcelain", "--", "helpers.R"))) > 0

out <- c(sprintf("# Event query plans: %s", label), "",
         sprintf("git %s%s, PostgreSQL %s, %s.", git(c("rev-parse", "--short", "HEAD")),
                 if (dirty) " (helpers.R modified)" else "",
                 dbGetQuery(con, "SHOW server_version")[[1]], format(Sys.Date())),
         "", "Generated by tests/benchmark/query_plans.R. Execution times are in ms, one per run; the plan is from the last run.", "")
summary <- data.frame(query = character(), ms = character())

for (query in queries) {
  message("Explaining: ", query$title)
  results <- lapply(seq_len(runs), function(i) explain(query$sql))
  times <- vapply(results, `[[`, numeric(1), "ms")
  summary[nrow(summary) + 1, ] <- list(query$title, paste(sprintf("%.1f", times), collapse = ", "))
  out <- c(out, sprintf("## %s", query$title), "",
           sprintf("Execution times: %s ms", paste(sprintf("%.1f", times), collapse = ", ")), "",
           "```sql", strsplit(as.character(query$sql), "\n")[[1]], "```", "",
           "```", results[[runs]]$plan, "```", "")
}

out <- append(out, c("| Query | Execution times (ms) |", "|---|---|",
                     sprintf("| %s | %s |", summary$query, summary$ms), ""),
              after = 6)

dir.create("tests/benchmark/query_plans", showWarnings = FALSE)
path <- sprintf("tests/benchmark/query_plans/%s.md", label)
writeLines(out, path)
message("Wrote ", path)
